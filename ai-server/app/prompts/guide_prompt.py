def build_guide_prompt(diary_text: str, style: str) -> str:
    if style not in STYLE_PROMPTS:
        raise ValueError("지원하지 않는 선화 스타일입니다.")

    return f"""
{COMMON_GUIDE_PROMPT}

[그림일기 내용]
{diary_text}

{STYLE_PROMPTS[style]}
"""